"""
Stemations Autonomous Orchestrator Agent
Coordinates Agent Skill ingestion, Gemma 4 reasoning, tool execution, and self-healing.
"""
from typing import Dict, Any, List, Callable, Optional
from harness.gemma_client import GemmaClient
from harness.tools.manim_tool import render_manim_code
from harness.tools.audio_tool import generate_voiceover
from harness.tools.compose_tool import compose_video_and_audio

class StemationsAgent:
    def __init__(self, model_name: str = "gemma-4-26b-a4b-it", log_callback: Optional[Callable[[str, str], None]] = None):
        """
        log_callback: Optional function (phase, message) to broadcast live trace updates to UI.
        """
        self.gemma = GemmaClient(model_name=model_name)
        self.log_callback = log_callback
        self.trace_history: List[Dict[str, str]] = []

    def _log(self, phase: str, message: str):
        entry = {"phase": phase, "message": message}
        self.trace_history.append(entry)
        if self.log_callback:
            self.log_callback(phase, message)
        else:
            print(f"[{phase}] {message}")

    def run(self, topic: str, max_repair_attempts: int = 1) -> Dict[str, Any]:
        """
        Runs the full autonomous generation cycle:
        1. Context & Skill ingestion
        2. Gemma 4 Script & Manim code synthesis
        3. Manim code compilation with self-healing critic loop
        4. Neural speech synthesis (edge-tts)
        5. Video & Audio composition
        6. Return output bundle with follow-up curriculum topics
        """
        self.trace_history.clear()
        
        # Step 1: Ingest Skill & Query Model
        self._log("SKILL_LOAD", "Loading Agent Skill 'stem-animator' (v1.0.0, 9:16 vertical)...")
        self._log("GEMMA_REASONING", f"Gemma 4 is synthesizing plan, script, and Manim code for: '{topic}'...")
        
        plan = self.gemma.generate_stemation(topic)
        
        script = plan.get("narration_script", "")
        manim_code = plan.get("manim_code", "")
        next_topics = plan.get("next_topics", [])
        
        self._log("SCRIPT_READY", f"Pedagogical Script generated ({len(script.split())} words).")
        self._log("CODE_READY", "Manim Community Edition scene code synthesized.")

        # Step 2: Render Manim Animation (with Self-Healing Loop)
        self._log("TOOL_MANIM", "Invoking tool_render_manim in sandboxed subprocess...")
        render_res = render_manim_code(manim_code)
        
        attempts = 0
        while not render_res["success"] and attempts < max_repair_attempts:
            attempts += 1
            error_msg = render_res["error"] or "Unknown render error"
            self._log(
                "SELF_HEAL",
                f"⚠️ Compiler error detected on attempt {attempts}! Feeding traceback back to Gemma 4 critic..."
            )
            
            # Feed compiler error back to Gemma 4
            manim_code = self.gemma.self_heal_manim_code(manim_code, error_msg)
            self._log("SELF_HEAL", "Corrected code generated by Gemma 4. Re-rendering...")
            render_res = render_manim_code(manim_code)

        if not render_res["success"]:
            self._log("ERROR", f"Render failed after {attempts} repair attempts: {render_res['error']}")
            return {
                "success": False,
                "error": render_res["error"],
                "trace": self.trace_history,
                "plan": plan
            }

        raw_video_path = render_res["video_path"]
        self._log("RENDER_SUCCESS", f"Manim scene rendered successfully at: {raw_video_path}")

        # Step 3: Synthesize Voiceover
        self._log("TOOL_TTS", "Invoking tool_generate_tts with edge-tts neural voice...")
        audio_res = generate_voiceover(script)
        
        if not audio_res["success"]:
            self._log("ERROR", f"Audio synthesis failed: {audio_res['error']}")
            # Graceful degradation: return raw video without audio if TTS fails
            return {
                "success": True,
                "video_path": raw_video_path,
                "audio_path": None,
                "script": script,
                "manim_code": manim_code,
                "next_topics": next_topics,
                "trace": self.trace_history
            }

        audio_path = audio_res["audio_path"]
        self._log("TTS_SUCCESS", f"Neural audio voiceover created at: {audio_path}")

        # Step 4: Compose Video & Audio
        self._log("TOOL_COMPOSE", "Invoking tool_compose_video: Synchronizing and stitching 9:16 MP4...")
        compose_res = compose_video_and_audio(raw_video_path, audio_path)
        
        final_video = compose_res["final_video_path"] if compose_res["success"] else raw_video_path
        self._log("COMPLETE", f"Stemation explainer video is ready: {final_video}")

        return {
            "success": True,
            "video_path": final_video,
            "audio_path": audio_path,
            "script": script,
            "manim_code": manim_code,
            "next_topics": next_topics,
            "trace": self.trace_history
        }
